const assert = require('node:assert/strict');
const { normalizeInput, normalizeProductionPlan, materializeCandidate, validateCandidate, candidateContractFor } = require('../server/services/creative/whiteboard/contracts');
const { buildSilentTiming, buildNarrationTiming, buildDisplayCaptions, letters } = require('../server/services/creative/whiteboard/narrationTiming');
const { OPENING_CUE_ID, narrationScenes, narrationCues, narrationOpeningDurationMs } = require('../server/services/creative/shared/videoOpening');
const { createTextPrompt } = require('../server/services/ai/doubaoTts');

const input = normalizeInput({ inputMode: 'text', content: '先画圆形。再画方形。', rewritePolicy: 'preserve', targetDurationSeconds: 15 });
const base = { schemaVersion: 1, title: '绘制顺序', summary: '按原文顺序绘图。',
  cues: [{ id: 'cue_1', text: '先画圆形。' }, { id: 'cue_2', text: '再画方形。' }],
  scenes: [{ id: 'scene_1', title: '第一步', cueIds: ['cue_1'], imagePrompt: '画面中央呈现一个圆形。' },
    { id: 'scene_2', title: '第二步', cueIds: ['cue_2'], imagePrompt: '画面中央呈现一个方形。' }] };
const old = materializeCandidate(base, input, {});
assert.equal(Object.hasOwn(old, 'opening'), false);
assert.deepEqual(normalizeInput({ ...input, opening: { mode: 'disabled' } }), input);
assert.deepEqual(candidateContractFor(input).schema.required, ['schemaVersion', 'title', 'summary', 'cues', 'scenes']);
const enabled = normalizeInput({ ...input, opening: { mode: 'question', question: '' } });
assert.ok(validateCandidate(base, enabled).some(error => error.includes('openingQuestion')));
const candidate = { ...base, openingQuestion: '怎么画？' };
assert.deepEqual(validateCandidate(candidate, enabled), []);
assert.ok(validateCandidate({ ...candidate, cues: [{ id: 'cue_1', text: '改写了正文。' }, base.cues[1]] }, enabled).some(error => error.includes('保留原文')));
assert.ok(validateCandidate(candidate, { ...enabled, opening: { mode: 'question', question: '为什么？' } }).some(error => error.includes('逐字')));
assert.throws(() => normalizeInput({ ...input, opening: { mode: 'unknown' } }));
assert.throws(() => normalizeInput({ ...input, opening: { mode: 'question', question: '。' } }));
assert.throws(() => normalizeInput({ ...input, opening: { mode: 'question', question: '字'.repeat(161) } }));
const artifact = materializeCandidate(candidate, enabled, {});
assert.equal(artifact.narrationText, '怎么画？\n先画圆形。\n再画方形。');
assert.deepEqual(artifact.cues, old.cues);
assert.equal(artifact.sourceTextSha256, old.sourceTextSha256);
const passages = narrationScenes(artifact);
assert.equal(passages[0].text, artifact.opening.question);
assert.equal(passages[0].startMs, 0);
assert.equal(passages[0].endMs, artifact.opening.estimatedDurationMs);
assert.deepEqual(passages.slice(1).map(scene => [scene.startMs, scene.endMs]),
  old.scenes.map(scene => [scene.startMs + 3000, scene.endMs + 3000]));
const prompt = createTextPrompt({ text: artifact.narrationText, scenes: passages });
const readText = [...prompt.matchAll(/「([^」]*)」/g)].map(match => match[1]).filter(Boolean).join('\n');
assert.equal(readText, artifact.narrationText);
assert.equal(prompt.split('「怎么画？」').length - 1, 1);
assert.deepEqual(narrationScenes(old).map(scene => [scene.startMs, scene.endMs]), old.scenes.map(scene => [scene.startMs, scene.endMs]));
const silent = buildSilentTiming(artifact);
assert.equal(silent.opening.endMs, 3000);
assert.equal(silent.durationMs, 18000);
assert.equal(silent.cues[0].id, OPENING_CUE_ID);
assert.equal(silent.cues[1].startMs, old.cues[0].startMs + 3000);
assert.equal(silent.scenes[0].startMs, 3000);
assert.ok(buildDisplayCaptions(artifact, silent, 72).length > 0);
const source = normalizeInput({ inputMode: 'srt', content: '1\n00:00:01,000 --> 00:00:04,000\n先画圆形。\n\n2\n00:00:05,000 --> 00:00:08,000\n再画方形。', opening: enabled.opening });
const srt = materializeCandidate(candidate, source, {});
const sourceTiming = buildSilentTiming(srt);
assert.equal(sourceTiming.cues[1].startMs, 4000);
assert.equal(sourceTiming.cues[1].endMs, 7000);
assert.equal(sourceTiming.cues[2].startMs, 8000);
assert.equal(sourceTiming.durationMs, 11000);
assert.ok(buildDisplayCaptions(srt, sourceTiming, 72).length > 0);
const words = letters(artifact.narrationText).map((text, i) => ({ text, start_time: i * 250 + 100, end_time: (i + 1) * 250 }));
const evidence = { provider: 'minimax', words };
const bodyOnly = { provider: 'minimax', words: letters(old.narrationText).map((text, i) => ({ text, start_time: i * 250 + 100, end_time: (i + 1) * 250 })) };
assert.throws(() => buildNarrationTiming(artifact, bodyOnly, 5000), error => error.code === 'NARRATION_TEXT_MISMATCH' && error.message.includes('缺少已确认的提问开场'));
const narrated = buildNarrationTiming(artifact, evidence, 5000);
assert.equal(narrated.opening.endMs, 800);
assert.equal(narrated.scenes[0].startMs, 800);
assert.equal(narrated.cues[1].startMs, 850);
assert.equal(narrated.cues[0].text, '怎么画？');
assert.ok(buildDisplayCaptions(artifact, narrated, 72, evidence).length > 0);
assert.deepEqual(buildSilentTiming(old).scenes.map(scene => scene.startMs), [0, 7500]);
console.log('PASS 提问合同、旧任务关闭兼容、原文保护、完整旁白、原生时间戳、静音/SRT 偏移及字幕重排');

const imageInput = normalizeInput({ ...input, opening: { mode: 'image-montage', question: '不能保留这个问题' } });
assert.deepEqual(imageInput.opening, { mode: 'image-montage' });
assert.deepEqual(candidateContractFor(imageInput).schema.required, candidateContractFor(input).schema.required);
assert.deepEqual(validateCandidate(base, imageInput), []);
const montage = materializeCandidate(base, imageInput, {});
assert.equal(montage.productionPlan.openingPlaybackMode, 'before-body');
assert.equal(normalizeProductionPlan({ openingPlaybackMode: 'overlay-body' }).openingPlaybackMode, 'overlay-body');
for (const value of [null, true, '', 'unknown']) assert.throws(() => normalizeProductionPlan({ openingPlaybackMode: value }), error => error.code === 'INVALID_INPUT');
const overlayMontage = materializeCandidate(base, imageInput, { openingPlaybackMode: 'overlay-body' });
assert.deepEqual(overlayMontage.opening, montage.opening, '播放方式不能改变开头/旁白身份输入');
assert.deepEqual(buildSilentTiming(overlayMontage), buildSilentTiming(montage), '播放方式只影响最终展示，不改写中间时间绑定');
assert.deepEqual(montage.cues, old.cues);
assert.deepEqual(montage.scenes, old.scenes);
assert.equal(montage.narrationText, old.narrationText);
assert.equal(montage.opening.estimatedDurationMs, 3000);
assert.equal(montage.opening.question, undefined);
assert.equal(narrationOpeningDurationMs(montage), 0);
assert.deepEqual(narrationScenes(montage), narrationScenes(old));
assert.deepEqual(narrationCues(montage), old.cues);
const imageSilent = buildSilentTiming(montage);
assert.equal(imageSilent.durationMs, 18000);
assert.equal(imageSilent.cues.length, old.cues.length);
assert.ok(imageSilent.captions.every(cue => cue.startMs >= 3000 && cue.sourceCueId !== OPENING_CUE_ID));
assert.ok(buildDisplayCaptions(montage, imageSilent, 72).length > 0);
const imageNative = buildNarrationTiming(montage, bodyOnly, 5000);
const bodyNative = buildNarrationTiming(old, bodyOnly, 5000);
assert.equal(imageNative.durationMs, 8000);
assert.equal(imageNative.audioOffsetMs, 3000);
assert.equal(imageNative.audioDurationMs, 5000);
assert.deepEqual(imageNative.scenes, bodyNative.scenes.map(scene => ({ ...scene, startMs: scene.startMs + 3000, endMs: scene.endMs + 3000 })));
assert.ok(buildDisplayCaptions(montage, imageNative, 72, bodyOnly).every(cue => cue.startMs >= 3000));
const imageSrt = materializeCandidate(base, { ...source, opening: imageInput.opening }, {});
const imageSource = buildSilentTiming(imageSrt);
assert.equal(imageSource.cues[0].startMs, 4000);
assert.equal(imageSource.cues[0].endMs, 7000);
assert.equal(imageSource.cues[1].startMs, 8000);
assert.equal(imageSource.durationMs, 11000);
assert.ok(buildDisplayCaptions(imageSrt, imageSource, 72).length > 0);
const { importBrowserModule } = require('./helpers/import-browser-module.cjs');
(async () => {
  const form = await importBrowserModule(require('path').join(__dirname, '../frontend-react/src/components/creative/whiteboard/whiteboardForm.js'));
  const opening = await importBrowserModule(require('path').join(__dirname, '../frontend-react/src/components/creative/shared/openingForm.js'));
  const draft = form.createWhiteboardDraft();
  draft.contents.topic = '验证开头';
  draft.opening = { mode: 'image-montage', question: '旧问题' };
  assert.equal(form.validateWhiteboardDraft(draft), '');
  assert.deepEqual(form.buildWhiteboardPayload(draft).input.opening, { mode: 'image-montage' });
  draft.productionPlan.openingPlaybackMode = 'overlay-body';
  assert.equal(form.buildWhiteboardPayload(draft).productionPlan.openingPlaybackMode, 'overlay-body');
  assert.equal(form.openingPlaybackLabel(overlayMontage), '从一开始绘制，开头覆盖在上层');
  assert.equal(form.imageOpeningOverlaysBody(artifact), false, '提问开头保留前置行为');
  assert.equal(form.openingPlaybackLabel({ ...montage, productionPlan: {} }), '开头结束后开始绘制');
  draft.productionPlan.openingPlaybackMode = 'invalid';
  assert.equal(form.validateWhiteboardDraft(draft), '请选择正文开始方式。');
  assert.deepEqual(opening.openingFormValue(montage), { mode: 'image-montage', question: '' });
  assert.equal(opening.validateOpening(draft.opening, { allowEmpty: false }), '');
  console.log('PASS 图片汇总：无提问/配音文本、前端提交与回填、原生/静音/SRT 顺延 3 秒及字号重排');
})().catch(error => { console.error(error); process.exitCode = 1; });
